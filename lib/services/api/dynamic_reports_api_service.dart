/// خدمة النماذج والتقارير الديناميكية عبر API (Dynamic Reports API Service)
class DynamicReportsApiService extends GetxService {
  Future<void> cleanLegacyAutoGeneratedTemplates() async {
    // No-op for SQL Server
  }
  Future<List<ReportApproval>> getApprovalTrail(int recordId) async {
    final response = await _client.get('/DynamicReports/records/$recordId/approvals');
    if (response.isSuccess && response.data is List) {
      return (response.data as List).map((e) => ReportApproval.fromMap(Map<String, dynamic>.from(e))).toList();
    }
    return [];
  }
  Future<void> addApproval({
    required int recordId,
    required String approvalStatus,
    String? rejectionReason,
    String? rejectedBy,
    dynamic correctiveAction,
    String? correctiveOwner,
    dynamic correctiveDueDate,
    String? gmDecision,
    String? gmDecisionBy,
    String? gmDecisionNotes,
    String? qsApprovedBy,
    String? qmApprovedBy,
    String? gmApprovedBy,
    String? actorName,
    String? actorPosition,
    int? actorUserId,
    String? sigToSave,
    DateTime? rejectedAt,
    String? rejectionCategory,
    String? severityLevel,
    String? rejectionNotes,
    String? affectedProducts,
    String? immediateAction,
    DateTime? qsApprovedAt,
    DateTime? qmApprovedAt,
    DateTime? gmApprovedAt,
    DateTime? gmDecisionAt,
  }) async {
    final body = {
      'action': (approvalStatus == 'Rejected' || approvalStatus == 'Rejected_By_GM')
          ? 'Rejected'
          : (approvalStatus == 'Returned' ? 'Returned' : 'Approved'),
      'approval_status': approvalStatus,
      'comments': rejectionReason ?? gmDecisionNotes ?? rejectionNotes ?? correctiveAction?.toString(),
      'corrective_action': correctiveAction?.toString(),
      'corrective_owner': correctiveOwner,
      'corrective_due_date': correctiveDueDate?.toString(),
      'gm_decision': gmDecision,
      'gm_decision_by': gmDecisionBy,
      'gm_decision_at': gmDecisionAt?.toIso8601String(),
      'gm_decision_notes': gmDecisionNotes,
      'rejection_reason': rejectionReason,
      'rejected_by': rejectedBy,
      'rejected_at': rejectedAt?.toIso8601String(),
      'rejection_category': rejectionCategory,
      'severity_level': severityLevel,
      'rejection_notes': rejectionNotes,
      'affected_products': affectedProducts,
      'immediate_action': immediateAction,
      'acted_by': actorName,
      'acted_by_user_id': actorUserId,
      'action_by_position': actorPosition,
      'signature_hash': sigToSave,
      'qs_approved_by': qsApprovedBy,
      'qs_approved_at': qsApprovedAt?.toIso8601String(),
      'qm_approved_by': qmApprovedBy,
      'qm_approved_at': qmApprovedAt?.toIso8601String(),
      'gm_approved_by': gmApprovedBy,
      'gm_approved_at': gmApprovedAt?.toIso8601String(),
    };
    await _client.writeQueued(
      'POST',
      '/DynamicReports/records/$recordId/approvals',
      body: body,
      entityType: 'dr_approval',
      entityId: recordId,
    );
  }
  static DynamicReportsApiService get to => Get.find<DynamicReportsApiService>();

  final ApiClient _client = ApiClient.to;

  /// جلب تصنيفات النماذج
  Future<List<DynamicReportCategory>> getCategories() async {
    final response = await _client.get('/DynamicReports/categories');
    if (response.isSuccess && response.data is List) {
      return (response.data as List).map((e) => DynamicReportCategory.fromMap(Map<String, dynamic>.from(e))).toList();
    }
    return [];
  }

  /// جلب قوالب النماذج
  Future<List<DynamicReport>> getTemplates({int? categoryId}) async {
    final response = await _client.get('/DynamicReports/templates', queryParams: {'categoryId': categoryId});
    if (response.isSuccess && response.data is List) {
      return (response.data as List).map((e) => DynamicReport.fromMap(Map<String, dynamic>.from(e))).toList();
    }
    return [];
  }

  /// جلب تفاصيل القالب مع الأقسام والحقول والإصدارات
  Future<DynamicReport?> getTemplateDetails(int id) async {
    final response = await _client.get('/DynamicReports/templates/$id');
    if (response.isSuccess && response.data is Map) {
      final map = Map<String, dynamic>.from(response.data);
      final reportMap = map['template'] ?? map['Template'] ?? map['report'] ?? map['Report'] ?? {};
      final sectionsList = map['sections'] ?? map['Sections'] ?? [];
      final fieldsList = map['fields'] ?? map['Fields'] ?? [];

      if (reportMap.isEmpty) return null;

      final report = DynamicReport.fromMap(Map<String, dynamic>.from(reportMap));
      final sections = (sectionsList as List).map((e) => DynamicReportSection.fromMap(Map<String, dynamic>.from(e))).toList();
      final fields = (fieldsList as List).map((e) => DynamicReportField.fromMap(Map<String, dynamic>.from(e))).toList();

      for (var section in sections) {
        section.fields = fields.where((f) => f.sectionId == section.id).toList();
      }
      report.sections = sections;
      return report;
    }
    return null;
  }

  /// جلب سجلات النماذج المعبأة
  Future<List<DynamicReportRecord>> getRecords({int? reportId, int? branchId}) async {
    final response = await _client.get('/DynamicReports/records', queryParams: {
      'reportId': reportId,
      'branchId': branchId,
    });
    if (response.isSuccess && response.data is List) {
      return (response.data as List).map((e) => DynamicReportRecord.fromMap(Map<String, dynamic>.from(e))).toList();
    }
    return [];
  }

  Future<Map<String, dynamic>> getDynamicReportStats({String timeframe = 'all', int? branchId}) async {
    final response = await _client.get('/DynamicReports/stats', queryParams: {
      'timeframe': timeframe,
      'branchId': branchId,
    });
    if (response.isSuccess && response.data is Map) {
      return Map<String, dynamic>.from(response.data);
    }
    return {
      'totalReports': 0,
      'totalRecords': 0,
      'approvedRecords': 0,
      'pendingQM': 0,
      'pendingGM': 0,
      'rejectedRecords': 0,
      'correctiveInProgress': 0,
      'pendingQMDecision': 0,
      'pendingGMDecision': 0,
      'compliantRecords': 0,
    };
  }

  Future<List<Map<String, dynamic>>> getPendingRecordsForRole(String roleStatus, {int? branchId}) async {
