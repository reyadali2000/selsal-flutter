    }
    return [];
  }

  Future<List<Map<String, dynamic>>> getCorrectiveActionRecords({int? branchId}) async {
    final response = await _client.get('/DynamicReports/records/corrective', queryParams: {
      'branchId': branchId,
    });
    if (response.isSuccess && response.data is List) {
      return (response.data as List).map((e) => Map<String, dynamic>.from(e)).toList();
    }
    return [];
  }

  /// جلب تفاصيل السجل وقيمه وتواقيع اعتماده
  Future<DynamicReportRecord?> getRecordDetails(int id) async {
    final data = await getRecordDetailsWithValues(id);
    return data?['record'] as DynamicReportRecord?;
  }

  Future<Map<String, dynamic>?> getRecordDetailsWithValues(int id) async {
    final response = await _client.get('/DynamicReports/records/$id');
    if (response.isSuccess && response.data is Map) {
      final map = Map<String, dynamic>.from(response.data);
      final recordMap = map['record'] ?? map['Record'] ?? {};
      final valuesList = map['values'] ?? map['Values'] ?? [];
      
      if (recordMap.isEmpty) return null;

      final record = DynamicReportRecord.fromMap(Map<String, dynamic>.from(recordMap));
      final values = (valuesList as List).map((e) => DynamicReportValue.fromMap(Map<String, dynamic>.from(e))).toList();
      
      return {
        'record': record,
        'values': values,
      };
    }
    return null;
  }

  // --- Template CRUD ---
  Future<void> deleteReport(int id) async {
    final res = await _client.delete('/DynamicReports/templates/$id');
    if (!res.isSuccess) {
      throw Exception(res.message);
    }
  }

  // --- Record CRUD ---
  Future<void> deleteRecord(int id) async {
    final res = await _client.writeQueued(
      'DELETE',
      '/DynamicReports/records/$id',
      entityType: 'dr_record',
      entityId: id,
    );
    if (!res.isSuccess) {
      throw Exception(res.message);
    }
  }

  Future<void> updateReport(DynamicReport report) async {
    final res = await _client.put('/DynamicReports/templates/${report.id}', body: report.toMap());
    if (!res.isSuccess) {
      throw Exception(res.message);
    }
  }

  Future<int> saveOrUpdateTemplate(DynamicReport report, List<DynamicReportSection> sections, List<DynamicReportField> fields) async {
    final payload = report.toMap();
    payload['sections'] = sections.map((s) {
      final secMap = s.toMap();
      secMap['fields'] = fields.where((f) => f.sectionId == s.id).map((f) => f.toMap()).toList();
      return secMap;
    }).toList();

    final response = await _client.post('/DynamicReports/templates', body: payload);
    if (!response.isSuccess) {
      throw Exception(response.message);
    }
    if (response.data != null) {
      if (response.data is int) return response.data as int;
      if (response.data is String) return int.tryParse(response.data.toString()) ?? 0;
    }
    return report.id ?? 0;
  }

  // --- Record CRUD ---
  Future<int> saveRecord(DynamicReportRecord record, List<DynamicReportValue> values) async {
    final body = record.toMap();
    body['values'] = values.map((v) => v.toMap()).toList();
    final response = await _client.writeQueued(
      'POST',
      '/DynamicReports/records',
      body: body,
      entityType: 'dr_record',
    );
    if (!response.isSuccess) {
      throw Exception(response.message);
    }
    if (response.data != null) {
      if (response.data is int) return response.data as int;
      if (response.data is String) return int.tryParse(response.data.toString()) ?? 0;
    }
    return record.id ?? 0;
  }
}



